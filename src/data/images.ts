export const IMAGE_BY_ID: Record<string, SiteImage> = Object.fromEntries(
  IMAGES.map((i) => [i.id, i]),
);

/** Look up an image by its brief ID (throws at build time if the ID is wrong). */
export function img(id: string): SiteImage {
  const found = IMAGE_BY_ID[id];
  if (!found) throw new Error(`Unknown image id: ${id}`);
  return found;
}

export function imgs(...ids: string[]): SiteImage[] {
  return ids.map(img);
}

/** Aspect ratio as width / height. */
export function aspectOf(image: SiteImage): number {
  return image.orientation === 'P' ? 3 / 4 : 4 / 3;
}

